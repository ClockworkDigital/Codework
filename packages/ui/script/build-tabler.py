"""Regenerate Tabler paths without changing the shared 256-unit icon API.

Run with Python packages skia-python==144.1 and fonttools==4.60.2 installed.
Tabler's round, 2-unit strokes are expanded into fill paths so existing inline
icons and SVG sprites render identically without a runtime dependency.
"""

import base64
import hashlib
import io
import json
import tarfile
import urllib.request
from pathlib import Path

import skia
from fontTools.pens.basePen import BasePen
from fontTools.svgLib.path import parse_path


class IconPen(BasePen):
    def __init__(self):
        super().__init__(None)
        self.path = skia.Path()

    def _moveTo(self, point):
        self.path.moveTo(*point)

    def _lineTo(self, point):
        self.path.lineTo(*point)

    def _curveToOne(self, first, second, end):
        self.path.cubicTo(*first, *second, *end)

    def _qCurveToOne(self, control, end):
        self.path.quadTo(*control, *end)

    def _closePath(self):
        self.path.close()


def coordinates(points):
    return " ".join(f"{coordinate:.2f}".rstrip("0").rstrip(".") for point in points for coordinate in point)


def serialize(path):
    commands = []
    iterator = iter(path)
    for verb, points in iterator:
        if verb == skia.Path.kMove_Verb:
            commands.append("M" + coordinates(points))
        elif verb == skia.Path.kLine_Verb:
            commands.append("L" + coordinates(points[1:]))
        elif verb == skia.Path.kQuad_Verb:
            commands.append("Q" + coordinates(points[1:]))
        elif verb == skia.Path.kCubic_Verb:
            commands.append("C" + coordinates(points[1:]))
        elif verb == skia.Path.kConic_Verb:
            quads = skia.Path.ConvertConicToQuads(*points, iterator.conicWeight(), 1)
            commands.extend("Q" + coordinates(quads[i:i + 2]) for i in range(1, len(quads), 2))
        elif verb == skia.Path.kClose_Verb:
            commands.append("Z")
        else:
            raise ValueError(f"Unsupported path verb: {verb}")
    return "".join(commands)


root = Path(__file__).resolve().parents[1] / "src/components"
provenance = json.loads((root / "tabler/provenance.json").read_text())
url = f"https://registry.npmjs.org/@tabler/icons/-/icons-{provenance['version']}.tgz"
archive = urllib.request.urlopen(url).read()
integrity = "sha512-" + base64.b64encode(hashlib.sha512(archive).digest()).decode()
if integrity != provenance["integrity"]:
    raise ValueError("Tabler package integrity mismatch")
with tarfile.open(fileobj=io.BytesIO(archive)) as package:
    nodes = json.load(package.extractfile("package/tabler-nodes-outline.json"))

paint = skia.Paint(
    Style=skia.Paint.kStroke_Style,
    StrokeWidth=provenance["strokeWidth"],
    StrokeCap=skia.Paint.kRound_Cap,
    StrokeJoin=skia.Paint.kRound_Join,
)
paths = {}
for name, source in provenance["mapping"].items():
    pen = IconPen()
    for tag, attributes in nodes[source]:
        if tag != "path":
            raise ValueError(f"Unsupported SVG element in {source}: {tag}")
        parse_path(attributes["d"], pen)
    expanded = skia.Path()
    if not paint.getFillPath(pen.path, expanded):
        raise ValueError(f"Could not expand {source}")
    expanded.transform(skia.Matrix.Scale(256 / 24, 256 / 24))
    paths[name] = serialize(expanded)

output = [
    "// Generated by script/build-tabler.py. Source and MIT licence: ./tabler/.",
    "// Expanded Tabler outline strokes preserve the shared 256-unit fill-path API.",
    "export const paths = {",
    *(f"  {json.dumps(name)}: {json.dumps(path)}," for name, path in paths.items()),
    "} as const",
    "",
    "export type IconName = keyof typeof paths",
    "",
    "// Preserve public icon names used by shared and legacy controls.",
    "export const icons = {",
    "  ...paths,",
    *(f"  {json.dumps(name)}: paths[{json.dumps(source)}]," for name, source in provenance["aliases"].items()),
    "} as const",
    "",
]
(root / "tabler.ts").write_text("\n".join(output))
print(f"Generated {len(paths)} Tabler icons and {len(provenance['aliases'])} aliases")
